// Writes marketplace/docker-mcp-registry/tools.json and marketplace/tools.md from the BUILT server
// (so listings never drift from the code). Run after `npm run build`.
import { Client, InMemoryTransport } from '@modelcontextprotocol/client';
import { readFileSync, writeFileSync } from 'node:fs';
import { buildDeps, createServer, loadConfig, DATA_TOOLS, TOOLSETS } from '../dist/index.js';

const config = loadConfig({ ...process.env, SITEVERDICT_DRY_RUN: '1', SITEVERDICT_TOOLSETS: 'all' });
const server = createServer({ ...buildDeps(config, () => {}), auth: { clientKey: 'export', source: 'none' } });
const [ct, st] = InMemoryTransport.createLinkedPair();
await server.connect(st);
const client = new Client({ name: 'export', version: '1.0.0' });
await client.connect(ct);
const { tools } = await client.listTools();
const { prompts } = await client.listPrompts();

const dockerTools = tools.map((t) => ({
  name: t.name,
  description: t.description,
  arguments: Object.entries(t.inputSchema.properties ?? {}).map(([name, s]) => ({
    name,
    type: s.type ?? (s.enum ? 'string' : 'string'),
    desc: s.description ?? '',
    ...(t.inputSchema.required?.includes(name) ? {} : { optional: true }),
  })),
}));
writeFileSync(new URL('../marketplace/docker-mcp-registry/tools.json', import.meta.url), JSON.stringify(dockerTools, null, 2) + '\n');

const toolsetOf = (name) => DATA_TOOLS.find((t) => t.name === name)?.toolsets.join(', ') ?? (name === 'get_run_results' ? '(any data toolset)' : 'web');
const secretsOf = (name) => (DATA_TOOLS.find((t) => t.name === name)?.secrets ?? []).map((x) => x.name).join(', ') || '—';
const md = ['<!-- generated by npm run export:tools; do not edit -->', '', '| Toolset | Title | Description |', '|---|---|---|']
  .concat(Object.entries(TOOLSETS).map(([id, t]) => `| \`${id}\` | ${t.title} | ${t.description} |`))
  .concat(['', '| Tool | Toolsets | Title | readOnly | destructive | openWorld | User credentials (optional) | Description |', '|---|---|---|---|---|---|---|---|'])
  .concat(tools.map((t) => `| \`${t.name}\` | ${toolsetOf(t.name)} | ${t.title} | ${t.annotations?.readOnlyHint} | ${t.annotations?.destructiveHint} | ${t.annotations?.openWorldHint} | ${secretsOf(t.name)} | ${t.description.replaceAll('|', '/')} |`))
  .concat(['', '| Prompt | Title |', '|---|---|'], prompts.map((p) => `| \`${p.name}\` | ${p.title} |`));
// MCPB manifest tool list (static, informational) stays in sync with the code.
const manifestUrl = new URL('../manifest.json', import.meta.url);
const manifest = JSON.parse(readFileSync(manifestUrl, 'utf8'));
manifest.tools = tools.map((t) => ({ name: t.name, description: t.title }));
writeFileSync(manifestUrl, JSON.stringify(manifest, null, 2) + '\n');
writeFileSync(new URL('../marketplace/tools.md', import.meta.url), md.join('\n') + '\n');
await client.close();
process.stdout.write(`exported ${tools.length} tools, ${prompts.length} prompts\n`);
